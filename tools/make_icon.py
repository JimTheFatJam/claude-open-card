#!/usr/bin/env python3
"""Generate the pixel-art Open Card icon (Android adaptive icon + SVG logo) from one pixel grid.

Run from the repository root:  python3 tools/make_icon.py
"""
import os

SPADE = ['....#....', '...###...', '..#####..', '.#######.', '#########', '#########', '.##.#.##.', '....#....', '...###...']
HEART = ['.##...##.', '####.####', '#########', '#########', '.#######.', '..#####..', '...###...', '....#....', '.........']
COLORS = {'o': '#0B0D10', 'w': '#FBFBF6', 's': '#D9D6C8', 'k': '#1B1B1B', 'r': '#C62828', 'h': '#59000000'}
W, H = 25, 22
CW, CH = 13, 17


def grid():
    g = [['.'] * W for _ in range(H)]

    def card(x0, y0, sprite, ink):
        # hard drop shadow (1px right/down)
        for y in range(y0 + 1, y0 + CH + 1):
            for x in range(x0 + 1, x0 + CW + 1):
                if 0 <= y < H and 0 <= x < W:
                    g[y][x] = 'h'
        for y in range(y0, y0 + CH):
            for x in range(x0, x0 + CW):
                edge = x in (x0, x0 + CW - 1) or y in (y0, y0 + CH - 1)
                shade = x == x0 + CW - 2 or y == y0 + CH - 2
                g[y][x] = 'o' if edge else ('s' if shade else 'w')
        sx, sy = x0 + 2, y0 + 4
        for j, row in enumerate(sprite):
            for i, ch in enumerate(row):
                if ch == '#':
                    g[sy + j][sx + i] = ink
        # corner pips: tiny 1px suit marks
        g[y0 + 2][x0 + 2] = ink
        g[y0 + CH - 3][x0 + CW - 3] = ink

    card(0, 0, SPADE, 'k')
    card(W - CW - 1, H - CH - 1, HEART, 'r')
    return g


def rects(g, key):
    """Merge horizontal runs of one colour into rectangles."""
    out = []
    for y, row in enumerate(g):
        x = 0
        while x < W:
            if row[x] == key:
                s = x
                while x < W and row[x] == key:
                    x += 1
                out.append((s, y, x - s))
            else:
                x += 1
    return out


def android_path(rs, scale, off, offy):
    return ' '.join(f'M{off + x * scale:g},{offy + y * scale:g}h{w * scale:g}v{scale:g}h{-w * scale:g}z' for x, y, w in rs)


def main():
    g = grid()
    order = ['h', 'o', 'w', 's', 'k', 'r']
    res = 'app/src/main/res'
    scale = 2.3
    off = (108 - W * scale) / 2  # x offset
    offy = (108 - H * scale) / 2
    paths = '\n'.join(
        f'    <path android:fillColor="{COLORS[k]}" android:pathData="{android_path(rects(g, k), scale, off, offy)}" />'
        for k in order if rects(g, k))
    with open(f'{res}/drawable/ic_launcher_foreground.xml', 'w') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icon.py: pixel-art Open Card icon -->\n'
                '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                '    android:width="108dp" android:height="108dp"\n'
                '    android:viewportWidth="108" android:viewportHeight="108">\n' + paths + '\n</vector>\n')
    # background: green felt with a 4dp dither checker
    checks = ' '.join(f'M{x * 4},{y * 4}h4v4h-4z' for y in range(27) for x in range(27) if (x + y) % 2 == 0)
    with open(f'{res}/drawable/ic_launcher_background.xml', 'w') as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_icon.py -->\n'
                '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
                '    android:width="108dp" android:height="108dp"\n'
                '    android:viewportWidth="108" android:viewportHeight="108">\n'
                '    <path android:fillColor="#17744A" android:pathData="M0,0h108v108h-108z" />\n'
                f'    <path android:fillColor="#1A000000" android:pathData="{checks}" />\n</vector>\n')
    # SVG logo for the home screen
    svg_paths = ''.join(
        f'<path fill="{COLORS[k] if k != "h" else "#000"}"{" fill-opacity=\".35\"" if k == "h" else ""} d="'
        + ''.join(f'M{x},{y}h{w}v1h-{w}z' for x, y, w in rects(g, k)) + '"/>'
        for k in order if rects(g, k))
    os.makedirs('app/src/main/assets/www/img', exist_ok=True)
    with open('app/src/main/assets/www/img/logo.svg', 'w') as f:
        f.write(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" shape-rendering="crispEdges">{svg_paths}</svg>\n')
    return g


if __name__ == '__main__':
    main()
